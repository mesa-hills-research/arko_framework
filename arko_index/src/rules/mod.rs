// Kind flags, per node kind id.
const DEFINITION: u16 = 1;
const CONTAINER: u16 = 1 << 1;
const ATTACH: u16 = 1 << 2;
const WRAPPER: u16 = 1 << 3;
const FAMILY: u16 = 1 << 4;
const COMPACT: u16 = 1 << 5;
const ATOMIC: u16 = 1 << 6;
const CALLABLE: u16 = 1 << 7;
const BINDING: u16 = 1 << 8;
const KEYED: u16 = 1 << 9;
const ATTACH_BACK: u16 = 1 << 10;

/// A table with its kinds resolved against the grammar: flags by node kind id.
pub(crate) struct Rules {
    pub(crate) table: &'static Table,
    flags: Vec<u16>,
}

impl Rules {
    fn new(table: &'static Table, language: &Language) -> Self {
        let count = language.node_kind_count();
        let mut flags = vec![0u16; count];
        for (id, slot) in flags.iter_mut().enumerate() {
            let Some(kind) = language.node_kind_for_id(id as u16) else {
                continue;
            };
            *slot = table.flags_of(kind);
        }
        Self { table, flags }
    }

    fn flags(&self, n: Node) -> u16 {
        self.flags.get(n.kind_id() as usize).copied().unwrap_or(0)
    }

    /// A definition: a listed or tags.scm kind, a binding of a callable, or a keyed kind
    /// whose key makes it one.
    pub(crate) fn definition(&self, n: Node, text: &str) -> bool {
        let f = self.flags(n);
        f & DEFINITION != 0
            || (f & BINDING != 0 && self.binds_callable(n))
            || (f & KEYED != 0
                && self
                    .keyed(n, text)
                    .is_some_and(|k| matches!(k.role, Role::Definition | Role::Container)))
    }

    pub(crate) fn container(&self, n: Node, text: &str) -> bool {
        let f = self.flags(n);
        f & CONTAINER != 0
            || (f & KEYED != 0
                && self
                    .keyed(n, text)
                    .is_some_and(|k| k.role == Role::Container))
    }

    /// Attaches forward: comments, the listed kinds, keyed attachments and, when the
    /// table says so, whitespace-only nodes.
    pub(crate) fn attaches(&self, n: Node, text: &str) -> bool {
        let f = self.flags(n);
        f & ATTACH != 0
            || (f & KEYED != 0 && self.keyed(n, text).is_some_and(|k| k.role == Role::Attach))
            || (self.table.attach_blank && text[n.byte_range()].trim().is_empty())
    }

    /// Whether `n`'s kind is a definition only under a condition (a binding or a keyed
    /// kind).
    pub(crate) fn conditional(&self, n: Node) -> bool {
        self.flags(n) & (BINDING | KEYED) != 0
    }

    pub(crate) fn attaches_back(&self, n: Node) -> bool {
        self.flags(n) & ATTACH_BACK != 0
    }

    pub(crate) fn wrapper(&self, n: Node) -> bool {
        self.flags(n) & WRAPPER != 0
    }

    pub(crate) fn family(&self, n: Node) -> bool {
        self.flags(n) & FAMILY != 0
    }

    pub(crate) fn compact(&self, n: Node) -> bool {
        self.flags(n) & COMPACT != 0
    }

    pub(crate) fn atomic(&self, n: Node) -> bool {
        self.flags(n) & ATOMIC != 0
    }

    fn binds_callable(&self, n: Node) -> bool {
        let kind = n.kind();
        self.table
            .bindings
            .iter()
            .filter(|(k, _)| *k == kind)
            .any(|(_, path)| resolve(n, path).is_some_and(|v| self.flags(v) & CALLABLE != 0))
    }

    /// The keyed rule that applies to `n`, if its key matches.
    pub(crate) fn keyed(&self, n: Node, text: &str) -> Option<&'static Keyed> {
        let kind = n.kind();
        self.table.keyed.iter().find(|k| {
            k.kind == kind
                && resolve(n, k.key).is_some_and(|key| k.values.contains(&&text[key.byte_range()]))
        })
    }

    /// The node holding `n`'s members: the kind's body path, or its `body` field.
    pub(crate) fn body<'t>(&self, n: Node<'t>) -> Option<Node<'t>> {
        let kind = n.kind();
        match self.table.bodies.iter().find(|(k, _)| *k == kind) {
            Some((_, path)) => resolve(n, path),
            None => n.child_by_field_name("body"),
        }
    }
}

impl Table {
    fn flags_of(&self, kind: &str) -> u16 {
        let has = |list: &[&str]| list.contains(&kind);
        let mut f = 0;
        let tagged = self.tags.iter().any(|(k, _)| *k == kind) && !has(self.skip_tags);
        if tagged || has(self.definitions) {
            f |= DEFINITION;
        }
        if has(self.containers) {
            f |= CONTAINER;
        }
        if kind.contains("comment") || has(self.attach) {
            f |= ATTACH;
        }
        if has(self.wrappers) {
            f |= WRAPPER;
        }
        if has(self.families) {
            f |= FAMILY;
        }
        if has(self.compact) {
            f |= COMPACT;
        }
        if has(self.atomic) {
            f |= ATOMIC;
        }
        if has(self.callables) {
            f |= CALLABLE;
        }
        if self.bindings.iter().any(|(k, _)| *k == kind) {
            f |= BINDING;
        }
        if has(self.attach_back) {
            f |= ATTACH_BACK;
        }
        if self.keyed.iter().any(|k| k.kind == kind) {
            f |= KEYED;
        }
        f
    }

    /// The default label keyword of a tags.scm definition: its category.
    pub(crate) fn tag_category(&self, kind: &str) -> Option<&'static str> {
        if self.skip_tags.contains(&kind) {
            return None;
        }
        self.tags.iter().find(|(k, _)| *k == kind).map(|(_, c)| *c)
    }
}

/// The node at `path` below `n`. Segments are separated by `/`:
/// - `field`: the child in that field;
/// - `#kind` or `#a|b`: the first named child of one of those kinds;
/// - `*`: the first named child;
/// - `~field`: the nearest node in that field among the named descendants, breadth
///   first, at most four levels down.
pub(crate) fn resolve<'t>(n: Node<'t>, path: &str) -> Option<Node<'t>> {
    let mut at = n;
    for segment in path.split('/') {
        at = if let Some(kinds) = segment.strip_prefix('#') {
            let mut cursor = at.walk();
            let found = at
                .named_children(&mut cursor)
                .find(|c| kinds.split('|').any(|k| k == c.kind()));
            found?
        } else if segment == "*" {
            let mut cursor = at.walk();
            let found = at.named_children(&mut cursor).find(|c| !c.is_extra());
            found?
        } else if let Some(field) = segment.strip_prefix('~') {
            nearest_field(at, field)?
        } else {
            at.child_by_field_name(segment)?
        };
    }
    Some(at)
}

fn nearest_field<'t>(n: Node<'t>, field: &str) -> Option<Node<'t>> {
    let mut level = vec![n];
    for _ in 0..4 {
        let mut next = Vec::new();
        for node in level {
            if let Some(found) = node.child_by_field_name(field) {
                return Some(found);
            }
            let mut cursor = node.walk();
            next.extend(node.named_children(&mut cursor));
        }
        level = next;
    }
    None
}

/// The rules of a parser key, resolved once per process.
pub(crate) fn rules(parser: &str) -> Option<&'static Rules> {
    static CACHE: OnceLock<Vec<OnceLock<Rules>>> = OnceLock::new();
    let index = crate::languages::PARSERS
        .iter()
        .position(|p| *p == parser)?;
    let cache = CACHE.get_or_init(|| {
        crate::languages::PARSERS
            .iter()
            .map(|_| OnceLock::new())
            .collect()
    });
    let language = crate::languages::grammar(parser)?;
    Some(cache[index].get_or_init(|| Rules::new(table(parser), &language)))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::languages::{PARSERS, grammar};

    /// Every kind and field a table names exists in its grammar, so a typo or a grammar
    /// upgrade that renames one fails here instead of silently matching nothing. The
    /// classic lists name the kinds of all nine grammars at once, so for the classic
    /// tables only their per-language fields are checked.
    #[test]
    fn every_kind_exists_in_its_grammar() {
        let mut errors = Vec::new();
        for parser in PARSERS {
            let t = table(parser);
            assert_eq!(t.key, *parser);
            let language = grammar(parser).unwrap();
            let kinds: std::collections::HashSet<&str> = (0..language.node_kind_count())
                .filter_map(|id| language.node_kind_for_id(id as u16))
                .collect();
            let mut named: Vec<&str> = Vec::new();
            let mut fields: Vec<&str> = Vec::new();
            let mut paths: Vec<&str> = Vec::new();
            for list in [t.members, t.fields, t.group_in, t.seams] {
                named.extend(list);
            }
            named.extend(t.breadcrumbs.iter().map(|(k, _)| *k));
            paths.extend(
                t.breadcrumbs
                    .iter()
                    .map(|(_, p)| *p)
                    .filter(|p| !p.is_empty()),
            );
            if !t.classic {
                named.extend(t.tags.iter().map(|(k, _)| *k));
                for list in [
                    t.skip_tags,
                    t.definitions,
                    t.containers,
                    t.attach,
                    t.attach_back,
                    t.wrappers,
                    t.callables,
                    t.declarators,
                    t.families,
                    t.compact,
                    t.atomic,
                ] {
                    named.extend(list);
                }
                named.extend(t.bindings.iter().map(|(k, _)| *k));
                named.extend(t.keyed.iter().map(|k| k.kind));
                named.extend(t.bodies.iter().map(|(k, _)| *k));
                named.extend(t.names.iter().map(|(k, _)| *k));
                named.extend(t.labels.iter().map(|(k, _)| *k));
                fields.extend(t.name_fields);
                paths.extend(t.bindings.iter().map(|(_, p)| *p));
                paths.extend(t.bodies.iter().map(|(_, p)| *p));
                paths.extend(t.names.iter().map(|(_, p)| *p));
                paths.extend(t.keyed.iter().map(|k| k.key));
                paths.extend(t.labels.iter().filter_map(|(_, l)| match l {
                    Label::Path(p) => Some(*p),
                    _ => None,
                }));
            }
            for path in paths {
                for segment in path.split('/') {
                    if let Some(list) = segment.strip_prefix('#') {
                        named.extend(list.split('|'));
                    } else if segment != "*" {
                        fields.push(segment.trim_start_matches('~'));
                    }
                }
            }
            for kind in named {
                if !kinds.contains(kind) {
                    errors.push(format!("{parser}: no node kind {kind:?}"));
                }
            }
            for field in fields {
                if language.field_id_for_name(field).is_none() {
                    errors.push(format!("{parser}: no field {field:?}"));
                }
            }
        }
        assert!(errors.is_empty(), "{}", errors.join("\n"));
    }
}
