//! The chunking rules of each grammar, as data for the engine in `syntax.rs`: which node
//! kinds are definitions (preferred boundaries, named in symbol paths and scopes), which
//! containers expose their members, what attaches forward, where names and bodies are,
//! and how scopes are labelled. `docs/arko_index-languages.md` describes each language.
//!
//! The nine languages arko_index parsed first (Rust, Python, TypeScript, TSX,
//! JavaScript, Go, Java, C, C++) share [`CLASSIC`], whose lists are the engine's
//! original kind lists, and keep their original scope labels: their output is frozen.
//! The other grammars start from what their `tags.scm` marks as definitions
//! (`tags.rs`, generated by `tools/gen_language_rules.py`) and are curated by hand.
mod tables;
// Some grammars' tags.scm lists are reference only: their tables name the
// definitions directly (see docs/arko_index-languages.md).
#[allow(dead_code)]
mod tags;

use std::sync::OnceLock;
use tree_sitter::{Language, Node};

pub(crate) use tables::table;

/// How a scope label is made from a node.
#[derive(Clone, Copy, Debug)]
pub(crate) enum Label {
    /// `keyword name` (`fn f`, `class C`); nothing when the node has no name.
    Keyword(&'static str),
    /// The name alone (a JSON key, a Make target).
    Name,
    /// The node's text up to its body (or all of it), whitespace collapsed, without a
    /// trailing `{`, `:`, `=` or `do` (`@media (min-width: 800px)`, `resource "a" "b"`).
    Header,
    /// The text at a path (see [`resolve`]), as [`Label::Header`] cleans it
    /// (`<section id="x">`).
    Path(&'static str),
    /// The node's first line, as [`Label::Header`] cleans it (`CREATE TABLE orders`).
    Line,
}

/// What a keyed kind is when its key matches.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum Role {
    /// A definition: a preferred boundary, named, kept whole when it fits.
    Definition,
    /// A definition whose body always exposes its members (a module).
    Container,
    /// Attached to the next unit, like a comment (`@doc` in Elixir).
    Attach,
}

/// A kind whose role depends on the text at a path: Elixir's `call` is a definition
/// when its target is `def` or `defmodule`, HTML's `element` when its tag is `section`.
#[derive(Clone, Copy, Debug)]
pub(crate) struct Keyed {
    pub(crate) kind: &'static str,
    /// The path of the key (see [`resolve`]).
    pub(crate) key: &'static str,
    pub(crate) values: &'static [&'static str],
    pub(crate) role: Role,
    /// When set, the label is `key name` (`def add`, `defmodule Shop.Cart`).
    pub(crate) key_label: bool,
}

/// What a grammar's files hold, for a size bound per kind of content.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum Content {
    Code,
    Prose,
    Data,
}

/// One grammar's rules. Kinds are node kind names (named or not, as the engine matched
/// strings before). Every list is checked against the grammar by the tests.
///
/// The fields after `classic` are for the next chunker steps (token bounds per kind of
/// content, breadcrumbs inside split definitions, grouping small members, splitting at
/// seams). The engine does not read them yet.
#[derive(Clone, Copy, Debug)]
pub(crate) struct Table {
    /// The grammar key (`languages::grammar`).
    #[allow(dead_code)]
    pub(crate) key: &'static str,
    /// tags.scm definitions `(kind, category)`; the category is the default label
    /// keyword.
    pub(crate) tags: &'static [(&'static str, &'static str)],
    /// tags.scm kinds that are not definitions here.
    pub(crate) skip_tags: &'static [&'static str],
    /// More definition kinds.
    pub(crate) definitions: &'static [&'static str],
    /// Kinds that always expose their members (a module, a class body).
    pub(crate) containers: &'static [&'static str],
    /// Kinds that attach forward, besides every kind whose name contains `comment`.
    pub(crate) attach: &'static [&'static str],
    /// Kinds that stay with the unit before them (closing tags, `end module`).
    pub(crate) attach_back: &'static [&'static str],
    /// Wrappers whose inner (last) definition is what they define (`decorated_definition`).
    pub(crate) wrappers: &'static [&'static str],
    /// `(kind, path)`: the kind is a definition when the node at the path is one of
    /// `callables` (`const f = () => {}`).
    pub(crate) bindings: &'static [(&'static str, &'static str)],
    pub(crate) callables: &'static [&'static str],
    pub(crate) keyed: &'static [Keyed],
    /// `(kind, path)`: where a kind's members are. Every other kind: its `body` field.
    pub(crate) bodies: &'static [(&'static str, &'static str)],
    /// Fields tried first for every kind's name.
    pub(crate) name_fields: &'static [&'static str],
    /// `(kind, path)`: the name of a kind, when no name field has one.
    pub(crate) names: &'static [(&'static str, &'static str)],
    /// Kinds named by C's declarator chain (`int *f(void)` names `f`).
    pub(crate) declarators: &'static [&'static str],
    /// Scope labels. A definition without one is labelled by its tags.scm category.
    pub(crate) labels: &'static [(&'static str, Label)],
    /// Callable kinds that can pair as a function family.
    pub(crate) families: &'static [&'static str],
    /// Containers kept whole while smaller than 700 bytes (a small class).
    pub(crate) compact: &'static [&'static str],
    /// Kinds kept whole when they fit, even if they contain definitions.
    pub(crate) atomic: &'static [&'static str],
    /// Split a node that fits when it contains definitions (code), or keep it whole and
    /// split only what exceeds the bound (prose, markup, data).
    pub(crate) split_small: bool,
    /// Whitespace-only units attach forward (Markdown's blank sections).
    pub(crate) attach_blank: bool,
    /// Adjacent definitions with the same name and kind merge while they fit (Haskell
    /// and Elixir write one function as several clauses).
    pub(crate) merge_clauses: bool,
    /// A short first part of a split definition (its header: `module Orders =`) joins
    /// the definition after it instead of staying a chunk of its own.
    pub(crate) join_header: bool,
    /// Packing joins only the units of the node being split, or the pieces of one of
    /// them, never the tail of one unit's pieces with the next unit (the end of one
    /// JSON key's value with the next key).
    pub(crate) pack_within_scope: bool,
    /// The packing bound inside containers.
    pub(crate) container_pack: usize,
    /// The original rules (`CLASSIC`): scope labels come from `syntax::classic_label`.
    pub(crate) classic: bool,
    /// Code, prose or data: which size bound applies.
    #[allow(dead_code)]
    pub(crate) content: Content,
    /// `(kind, path)`: kinds that continue the scope chain inside a split definition
    /// (match arms, conditionals, loops, closures, inner functions). The label is the
    /// node's text up to the node at the path, as `Label::Header` cleans it
    /// (`if let Some(guard) = overflow_guard`, `ToolCall { .. } =>`); an empty path
    /// takes the first line.
    #[allow(dead_code)]
    pub(crate) breadcrumbs: &'static [(&'static str, &'static str)],
    /// Members that can group when small and adjacent (methods, functions).
    #[allow(dead_code)]
    pub(crate) members: &'static [&'static str],
    /// Field and property declarations, which stay with the members next to them.
    #[allow(dead_code)]
    pub(crate) fields: &'static [&'static str],
    /// Containers inside which small members group (impl, class, module bodies).
    #[allow(dead_code)]
    pub(crate) group_in: &'static [&'static str],
    /// Preferred split points inside a large definition (statements, match arms).
    #[allow(dead_code)]
    pub(crate) seams: &'static [&'static str],
}

